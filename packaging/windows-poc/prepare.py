"""Windows-only POC builder. Candidate locks are outputs, never claimed reviewed."""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from urllib.parse import urlparse, quote
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[2]


def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda: f.read(8 * 1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def fetch(url, path, sha):
    with urlopen(url, timeout=120) as response, path.open('wb') as out:
        shutil.copyfileobj(response, out, 8 * 1024 * 1024)
    if digest(path) != sha:
        raise ValueError(f'Hash mismatch: {path}')


# Independently confirmed official PyPI digest, scoped to the exact resolved wheel.
# https://pypi.org/pypi/Jinja2/3.1.6/json
MISSING_WHEEL_HASHES = {
    ('jinja2', '3.1.6', 'https://download.pytorch.org/whl/jinja2-3.1.6-py3-none-any.whl'):
        '85ece4451f492d0c13c5dd7c13a64681a86afae63a5f347908daf103ce6d2f67',
}


def wheel_sha256(entry, verification_dir):
    download = entry['download_info']
    url = download['url']
    parsed = urlparse(url)
    if (parsed.scheme != 'https' or parsed.hostname not in
            {'files.pythonhosted.org', 'download.pytorch.org', 'download-r2.pytorch.org'}
            or not parsed.path.endswith('.whl')):
        raise ValueError(f'Untrusted wheel source: {url}')
    sha = download.get('archive_info', {}).get('hashes', {}).get('sha256')
    key = (re.sub(r'[-_.]+', '-', entry['metadata']['name']).lower(),
           entry['metadata']['version'], url)
    trusted = MISSING_WHEEL_HASHES.get(key)
    if sha is None:
        if trusted is None:
            raise ValueError(f'No trusted SHA256 for wheel: {key}')
        # A matching filename is insufficient: verify bytes from the resolved URL.
        with tempfile.TemporaryDirectory(prefix='wheel-hash-', dir=verification_dir) as tmp:
            fetch(url, Path(tmp) / 'resolved.whl', trusted)
        sha = trusted
    if not isinstance(sha, str) or not re.fullmatch('[0-9a-f]{64}', sha):
        raise ValueError(f'Invalid wheel SHA256: {key}')
    if trusted is not None and sha != trusted:
        raise ValueError(f'Wheel SHA256 disagrees with trusted digest: {key}')
    return sha


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--work', type=Path, required=True)
    p.add_argument('--resolved-report', type=Path, help='Reviewed Beta candidate report; no new resolution')
    args = p.parse_args()
    work = args.work.resolve()
    assert sys.platform == 'win32' and sys.version_info[:3] == (3, 12, 15)
    evidence = work / 'evidence'
    py = Path(sys.executable).resolve()
    assert py.is_relative_to(work / 'runtime')
    def run(*args):
        subprocess.run([str(py), '-I', *map(str, args)], check=True, cwd=work)
    # Pin bootstrap using the existing platform-independent production lock.
    run('-m', 'pip', 'install', '--no-cache-dir', '--require-hashes',
        '--only-binary=:all:', '-r', ROOT / 'docker/pip-bootstrap.lock')
    baseline = (ROOT / 'requirements/docker-cpu-py312-linux-amd64.lock').read_text(encoding="utf-8")
    pins = dict(re.findall(r'^([\w-]+)==([^\s\\]+)', baseline, re.M))
    pins['torch'] = '2.14.1+cpu'
    constraints = evidence / 'production-constraints.txt'
    constraints.write_text(''.join(f'{k}=={v}\n' for k, v in sorted(pins.items())), encoding="utf-8")
    report = evidence / 'resolve.json'
    if args.resolved_report:
        shutil.copyfile(args.resolved_report, report)
    else:
        run('-m', 'pip', 'install', '--dry-run', '--ignore-installed', '--no-cache-dir',
            '--only-binary=:all:', '--index-url', 'https://pypi.org/simple',
            '--extra-index-url', 'https://download.pytorch.org/whl/cpu',
            '--report', report, '-r', constraints)
    entries = json.loads(report.read_text(encoding="utf-8"))['install']
    resolved = {re.sub(r'[-_.]+', '-', e['metadata']['name']).lower(): e['metadata']['version'] for e in entries}
    for name, version in pins.items():
        if resolved.get(re.sub(r'[-_.]+', '-', name).lower()) != version:
            raise ValueError(f'Candidate report changed fixed dependency: {name}=={version}')
    lock = evidence / 'windows-candidate.lock'
    lines = ['# UNREVIEWED: generated by native Windows pip resolution.\n']
    offline_lines = []
    for entry in entries:
        url = entry['download_info']['url']
        sha = wheel_sha256(entry, work)
        lines.append(f"{entry['metadata']['name']} @ {url} --hash=sha256:{sha}\n")
        offline_lines.append(f"{entry['metadata']['name']}=={entry['metadata']['version']} --hash=sha256:{sha}\n")
    lock.write_text(''.join(lines), encoding="utf-8")
    offline_lock = evidence / 'windows-offline-candidate.lock'
    offline_lock.write_text(''.join(offline_lines), encoding="utf-8")
    wheels = work / 'wheels'
    run('-m', 'pip', 'download', '--no-cache-dir', '--require-hashes', '--only-binary=:all:',
        '--dest', wheels, '-r', lock)
    run('-m', 'pip', 'install', '--no-cache-dir', '--no-index', '--find-links', wheels,
        '--require-hashes', '--only-binary=:all:', '-r', offline_lock)
    with (evidence / 'pip-check.txt').open('w', encoding="utf-8") as out:
        subprocess.run([str(py), '-I', '-m', 'pip', 'check'], stdout=out, stderr=subprocess.STDOUT, check=True)
    (evidence / 'wheel-sha256.json').write_text(json.dumps({x.name: digest(x) for x in wheels.iterdir()}, indent=2), encoding="utf-8")
    # Resources follow Linux Standalone layout; deliberately no Launcher/service start.
    bundle = work / 'bundle'
    bundle.mkdir()
    for name in ('app', 'web'):
        shutil.copytree(ROOT / name, bundle / name, ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
    for name in ('release.jsonc', 'LICENSE', 'NOTICE', 'THIRD_PARTY_NOTICES.md'):
        shutil.copy2(ROOT / name, bundle / name)
    licenses = bundle / 'licenses/runtime'
    licenses.mkdir(parents=True)
    env = dict(re.findall(r'^(\w+)=(.*)$', (ROOT / 'packaging/standalone/runtime.env').read_text(encoding="utf-8"), re.M))
    for key in ('PYTHON_LICENSE', 'OPENSSL_LICENSE'):
        fetch(env[key + '_URL'], licenses / env[key + '_FILE'], env[key + '_SHA256'])
    spec = importlib.util.spec_from_file_location('model_package', ROOT / 'docker/package_model.py')
    model_package = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(model_package)
    model = model_package.MANIFEST
    snapshot = bundle / 'models' / model['revision']
    snapshot.mkdir(parents=True)
    for record in model['files']:
        dest = snapshot / record['path']
        dest.parent.mkdir(parents=True, exist_ok=True)
        fetch(f"https://huggingface.co/{model['model']}/resolve/{model['revision']}/{quote(record['path'])}", dest, record['sha256'])
        model_package.verify(dest, record)
    shutil.copytree(ROOT / 'docker/licenses', bundle / 'licenses/model')
    shutil.copy2(ROOT / 'docker/bge-m3-manifest.json', bundle / 'models/manifest.json')
    # PowerShell relocates PBS only after this interpreter exits (Windows image locks).
    inputs = [ROOT / 'docker/pip-bootstrap.lock', ROOT / 'requirements/docker-cpu-py312-linux-amd64.lock',
              ROOT / 'docker/bge-m3-manifest.json', ROOT / 'packaging/standalone/runtime.env',
              *Path(__file__).parent.glob('*.*')]
    if args.resolved_report:
        inputs.append(args.resolved_report.resolve())
    manifest = {'source_commit': subprocess.check_output(['git', '-C', str(ROOT), 'rev-parse', 'HEAD'], text=True).strip(),
                'input_sha256': {str(x.relative_to(ROOT)): digest(x) for x in inputs},
                'resources': {str(x.relative_to(bundle)): digest(x) for x in bundle.rglob('*') if x.is_file()},
                'lock_status': 'native candidate; requires maintainer review', 'model_revision': model['revision']}
    (evidence / 'build-manifest.json').write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    (evidence / 'runtime-sha256.json').write_text(json.dumps({str(x.relative_to(work / 'runtime')): digest(x) for x in (work / 'runtime').rglob('*') if x.is_file()}, indent=2), encoding="utf-8")


if __name__ == '__main__':
    main()
