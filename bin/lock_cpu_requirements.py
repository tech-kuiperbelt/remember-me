#!/usr/bin/env python3
"""Resolve production inputs and hash only wheels selected for Linux CPython 3.12.

Run in a separate tooling venv with pip==24.0 and pip-tools==7.6.2.
Uses pip's installation report (dry run, ignoring installed packages), never a
freeze of the tooling or application environment. --upgrade deliberately refreshes pins.
"""
import argparse
from importlib.metadata import version
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import tempfile
from urllib.parse import unquote, urlsplit

from packaging.utils import parse_wheel_filename


ROOT = Path(__file__).resolve().parents[1]
LOCK = ROOT / "requirements/docker-cpu-py312-linux-amd64.lock"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upgrade", action="store_true")
    args = parser.parse_args()
    if (sys.version_info[:2] != (3, 12) or sys.platform != "linux"
            or platform.machine() != "x86_64" or platform.python_implementation() != "CPython"):
        parser.error("Resolve on Linux AMD64 / CPython 3.12")
    if version("pip") != "24.0" or version("pip-tools") != "7.6.2":
        parser.error("Use a tooling venv with pip==24.0 and pip-tools==7.6.2")
    with tempfile.TemporaryDirectory(prefix="remember-me-lock-") as directory:
        plain = Path(directory) / "resolved.txt"
        report = Path(directory) / "report.json"
        if LOCK.exists():
            shutil.copyfile(LOCK, plain)
        command = [sys.executable, "-m", "piptools", "compile", "requirements/docker-cpu.in",
                   "--resolver=backtracking", "--allow-unsafe", "--strip-extras", "--no-header",
                   "--no-annotate", "--no-emit-index-url", "--no-emit-trusted-host",
                   "--index-url", "https://pypi.org/simple",
                   "--pip-args=--only-binary=:all:", "--output-file", str(plain)]
        if os.environ.get("PIP_CACHE_DIR"):
            command.extend(["--cache-dir", os.environ["PIP_CACHE_DIR"]])
        if args.upgrade:
            command.append("--upgrade")
        subprocess.run(command, cwd=ROOT, check=True)
        subprocess.run([sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed",
                        "--only-binary=:all:", "--index-url", "https://pypi.org/simple",
                        "--report", str(report), "-r", str(plain)], cwd=ROOT, check=True)
        packages = json.loads(report.read_text())["install"]
    lines = ["# Generated by bin/lock_cpu_requirements.py; do not edit.",
             "# CPython 3.12 / Linux AMD64 / glibc >=2.34; pip 24.0 + pip-tools 7.6.2.",
             "# One SHA256 per selected wheel; production install must use --require-hashes.",
             "--index-url https://pypi.org/simple", ""]
    for package in sorted(packages, key=lambda p: p["metadata"]["name"].lower()):
        name = re.sub(r"[-_.]+", "-", package["metadata"]["name"]).lower()
        installed_version = package["metadata"]["version"]
        info = package["download_info"]
        url = info["url"]
        digest = info["archive_info"]["hashes"]["sha256"]
        if not re.fullmatch(r"[0-9a-f]{64}", digest) or not urlsplit(url).path.endswith(".whl"):
            raise SystemExit(f"Missing binary wheel/SHA256: {name}")
        filename = unquote(Path(urlsplit(url).path).name)
        _, _, _, tags = parse_wheel_filename(filename)
        compatible = False
        for tag in tags:
            match = re.fullmatch(r"manylinux_2_(\d+)_x86_64", tag.platform)
            if tag.platform in ("any", "manylinux2014_x86_64") or (match and int(match[1]) <= 34):
                compatible = True
        if not compatible:
            raise SystemExit(f"Wheel exceeds the glibc 2.34 AMD64 baseline: {filename}")
        if name.startswith(("nvidia-", "cuda-", "onnx", "fastembed")) or "triton" in name or name == "pytest":
            raise SystemExit(f"Non-production dependency: {name}")
        requirement = f"{name}=={installed_version}"
        if name == "torch":
            if not url.startswith("https://download-r2.pytorch.org/whl/cpu/") or "+cpu" not in installed_version:
                raise SystemExit("Torch must come from the official CPU wheel")
            requirement = f"torch @ {url}"
        lines.extend([f"# {filename}",
                      f"{requirement} \\", f"    --hash=sha256:{digest}"])
    if not any(p["metadata"]["name"].lower() == "torch" for p in packages):
        raise SystemExit("Missing Torch")
    LOCK.write_text("\n".join(lines) + "\n")
    print(f"Locked {len(packages)} production wheels: {LOCK}")


if __name__ == "__main__":
    main()
