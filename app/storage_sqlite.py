"""SQLite storage — authoritative primary with Outbox sync protocol."""

import json
import sqlite3
import pickle
import threading
import logging

logger = logging.getLogger("storage_sqlite")

from .storage import MemoryStorage, _now, _new_id, _cosine_similarity, DEFAULT_NAMESPACE


class SQLiteStorage(MemoryStorage):
    def __init__(self, path: str = "data/memories.db"):
        self.path = path
        self._lock = threading.RLock()
        self.conn = sqlite3.connect(path, check_same_thread=False)
        self.conn.row_factory = sqlite3.Row
        self._init_db()

    def _init_db(self):
        self.conn.executescript("""
            PRAGMA journal_mode=WAL;
            PRAGMA synchronous=NORMAL;

            CREATE TABLE IF NOT EXISTS memories (
                id TEXT PRIMARY KEY,
                text TEXT NOT NULL,
                embedding BLOB,
                metadata TEXT NOT NULL DEFAULT '{}',
                namespace TEXT NOT NULL DEFAULT 'default',
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                deleted INTEGER NOT NULL DEFAULT 0
            );
            CREATE INDEX IF NOT EXISTS idx_memories_namespace ON memories(namespace);
            CREATE INDEX IF NOT EXISTS idx_memories_created_at ON memories(created_at);
            CREATE INDEX IF NOT EXISTS idx_memories_updated_at ON memories(updated_at);
        """)
        # Migration for existing DBs without `deleted` column
        try:
            self.conn.execute("ALTER TABLE memories ADD COLUMN deleted INTEGER NOT NULL DEFAULT 0")
        except sqlite3.OperationalError:
            pass  # column already exists
        # Migration: outbox synced column (format-agnostic, not tied to JSON)
        try:
            self.conn.execute("ALTER TABLE memories ADD COLUMN synced INTEGER NOT NULL DEFAULT 0")
        except sqlite3.OperationalError:
            pass  # column already exists
        # Migration: summary column (nullable, generated by LLM)
        try:
            self.conn.execute("ALTER TABLE memories ADD COLUMN summary TEXT")
        except sqlite3.OperationalError:
            pass  # column already exists
        # Composite index for outbox polling: WHERE synced=0 ORDER BY updated_at
        self.conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_memories_synced_updated "
            "ON memories(synced, updated_at)"
        )
        # Keywords: global canonical vocabulary + many-to-many association.
        # These tables are a REBUILDABLE query index — the authoritative data
        # lives in memories.metadata["keywords"]. They are not backed up to
        # the JSONL replica and are rebuilt from metadata after recover/import.
        self.conn.executescript("""
            CREATE TABLE IF NOT EXISTS keywords (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                name TEXT UNIQUE NOT NULL
            );
            CREATE TABLE IF NOT EXISTS memory_keywords (
                memory_id TEXT NOT NULL,
                keyword_id INTEGER NOT NULL,
                PRIMARY KEY (memory_id, keyword_id)
            );
            CREATE INDEX IF NOT EXISTS idx_memory_keywords_keyword
                ON memory_keywords(keyword_id);
        """)
        self.conn.commit()

    def _serialize(self, emb: list[float]) -> bytes:
        return pickle.dumps(emb)

    def _deserialize(self, blob: bytes) -> list[float]:
        return pickle.loads(blob) if blob else []

    def _row_to_dict(self, row: sqlite3.Row) -> dict:
        d = dict(row)
        d["embedding"] = self._deserialize(d["embedding"])
        d["metadata"] = json.loads(d["metadata"])
        return d

    # -- keyword index helpers (SQLite-only, rebuildable from metadata) --

    @staticmethod
    def _extract_keywords(metadata: dict) -> list[str]:
        """Extract normalized keywords from a metadata dict.

        Filter: keep only non-empty strings. Normalize: strip + lowercase +
        deduplicate. Returns [] when absent/invalid.
        """
        raw = (metadata or {}).get("keywords")
        if not isinstance(raw, list):
            return []
        result = []
        seen = set()
        for kw in raw:
            if not isinstance(kw, str):
                continue
            kw = kw.strip().lower()
            if kw and kw not in seen:
                seen.add(kw)
                result.append(kw)
        return result

    def _sync_keyword_index(self, memory_id: str, metadata: dict):
        """Replace a memory's keyword associations (delete-then-insert).

        Caller must hold ``self._lock`` and is responsible for committing.
        """
        self.conn.execute(
            "DELETE FROM memory_keywords WHERE memory_id = ?", (memory_id,)
        )
        for name in self._extract_keywords(metadata):
            self.conn.execute(
                "INSERT OR IGNORE INTO keywords (name) VALUES (?)", (name,)
            )
            row = self.conn.execute(
                "SELECT id FROM keywords WHERE name = ?", (name,)
            ).fetchone()
            if row is not None:
                self.conn.execute(
                    "INSERT OR IGNORE INTO memory_keywords (memory_id, keyword_id) "
                    "VALUES (?, ?)", (memory_id, row["id"]),
                )

    def _remove_keyword_associations(self, memory_id: str):
        """Remove a memory's keyword associations. Caller holds _lock."""
        self.conn.execute(
            "DELETE FROM memory_keywords WHERE memory_id = ?", (memory_id,)
        )

    def _rebuild_keyword_index(self) -> int:
        """Clear both keyword tables and rebuild from memories.metadata.

        Caller must hold ``self._lock`` and is responsible for committing.
        Returns the number of (memory, keyword) associations created.
        """
        self.conn.execute("DELETE FROM memory_keywords")
        self.conn.execute("DELETE FROM keywords")
        rows = self.conn.execute(
            "SELECT id, metadata FROM memories WHERE deleted = 0"
        ).fetchall()
        associations = 0
        for row in rows:
            try:
                metadata = json.loads(row["metadata"] or "{}")
            except json.JSONDecodeError:
                continue
            names = self._extract_keywords(metadata)
            if not names:
                continue
            for name in names:
                self.conn.execute(
                    "INSERT OR IGNORE INTO keywords (name) VALUES (?)", (name,)
                )
                kw = self.conn.execute(
                    "SELECT id FROM keywords WHERE name = ?", (name,)
                ).fetchone()
                if kw is not None:
                    self.conn.execute(
                        "INSERT OR IGNORE INTO memory_keywords (memory_id, keyword_id) "
                        "VALUES (?, ?)", (row["id"], kw["id"]),
                    )
                    associations += 1
        return associations

    def rebuild_keyword_index(self) -> dict:
        """Public: clear and rebuild the keyword index from all active memories."""
        with self._lock:
            associations = self._rebuild_keyword_index()
            self.conn.commit()
        logger.info("keyword index rebuilt: %d associations", associations)
        return {"keyword_index_rebuilt": associations}

    def _keyword_counts(self) -> dict[str, int]:
        """Return {keyword_name: number_of_memories} for active memories."""
        rows = self.conn.execute(
            "SELECT k.name, COUNT(DISTINCT mk.memory_id) AS cnt "
            "FROM keywords k "
            "JOIN memory_keywords mk ON mk.keyword_id = k.id "
            "JOIN memories m ON m.id = mk.memory_id "
            "WHERE m.deleted = 0 "
            "GROUP BY k.name "
            "ORDER BY cnt DESC, k.name ASC"
        ).fetchall()
        return {r["name"]: r["cnt"] for r in rows}

    def get_keyword_vocabulary(self, namespace: str | None = None) -> list[str]:
        """Return the full keyword vocabulary (names only), ordered by frequency.

        Used by the deepseek migration to seed the candidate list so new
        records converge toward existing word forms. The index is rebuildable
        from memories.metadata, so this is safe to call at any time.
        """
        if namespace:
            rows = self.conn.execute(
                "SELECT k.name FROM keywords k "
                "JOIN memory_keywords mk ON mk.keyword_id = k.id "
                "JOIN memories m ON m.id = mk.memory_id "
                "WHERE m.deleted = 0 AND m.namespace = ? "
                "GROUP BY k.name ORDER BY COUNT(DISTINCT mk.memory_id) DESC, k.name ASC",
                (namespace,),
            ).fetchall()
        else:
            rows = self.conn.execute(
                "SELECT k.name FROM keywords k "
                "JOIN memory_keywords mk ON mk.keyword_id = k.id "
                "JOIN memories m ON m.id = mk.memory_id "
                "WHERE m.deleted = 0 "
                "GROUP BY k.name ORDER BY COUNT(DISTINCT mk.memory_id) DESC, k.name ASC"
            ).fetchall()
        return [r["name"] for r in rows]

    # -- internal sync protocol --

    def _add_with_id(self, memory_id, text, embedding, metadata, namespace,
                     created_at, updated_at, summary=None):
        """Insert/replace with explicit ID. Internal use only (sync/recovery).
        Sets synced=1 because data is already in (or being restored from) secondary.
        Uses INSERT OR REPLACE so that soft-deleted records can be restored.
        """
        with self._lock:
            self.conn.execute(
                "INSERT OR REPLACE INTO memories "
                "(id, text, embedding, metadata, namespace, created_at, updated_at, deleted, synced, summary) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, 0, 1, ?)",
                (memory_id, text, self._serialize(embedding),
                 json.dumps(metadata or {}), namespace, created_at, updated_at, summary),
            )
            self._sync_keyword_index(memory_id, metadata or {})
            self.conn.commit()

    # -- internal sync protocol (outbox pattern) --

    def _get_unsynced(self, limit=500):
        """Return records with synced=0 (including deleted), ordered by updated_at.
        Internal use only (DualStorage outbox sync job).
        """
        with self._lock:
            rows = self.conn.execute(
                "SELECT * FROM memories WHERE synced = 0 ORDER BY updated_at ASC LIMIT ?",
                (limit,),
            ).fetchall()
        return [self._row_to_dict(r) for r in rows]

    def _mark_synced_batch(self, memory_ids):
        """Batch-mark records as synced. Internal use only."""
        if not memory_ids:
            return
        with self._lock:
            placeholders = ",".join(["?"] * len(memory_ids))
            self.conn.execute(
                f"UPDATE memories SET synced = 1 WHERE id IN ({placeholders})",
                memory_ids,
            )
            self.conn.commit()

    def _count_unsynced(self) -> int:
        """Count active records awaiting sync. Internal use only (stats)."""
        with self._lock:
            return self.conn.execute(
                "SELECT COUNT(*) FROM memories WHERE synced = 0 AND deleted = 0"
            ).fetchone()[0]

    # -- public API --

    def add(self, text, embedding, metadata=None, namespace=DEFAULT_NAMESPACE, summary=None):
        """Insert a memory; dedup on (namespace, text). Returns {"id", "created"}."""
        with self._lock:
            existing = self.conn.execute(
                "SELECT id FROM memories WHERE namespace = ? AND text = ? AND deleted = 0 LIMIT 1",
                (namespace, text),
            ).fetchone()
            if existing:
                return {"id": existing[0], "created": False}
            eid = _new_id()
            now = _now()
            self.conn.execute(
                "INSERT INTO memories (id, text, embedding, metadata, namespace, created_at, updated_at, synced, summary) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, 0, ?)",
                (eid, text, self._serialize(embedding), json.dumps(metadata or {}), namespace, now, now, summary),
            )
            self._sync_keyword_index(eid, metadata or {})
            self.conn.commit()
        return {"id": eid, "created": True}

    def search(self, query_embedding, k=5, threshold=0.0, namespace=None):
        with self._lock:
            if namespace:
                rows = self.conn.execute(
                    "SELECT * FROM memories WHERE namespace = ? AND deleted = 0", (namespace,)
                ).fetchall()
            else:
                rows = self.conn.execute(
                    "SELECT * FROM memories WHERE deleted = 0"
                ).fetchall()
        scored = []
        for row in rows:
            emb = self._deserialize(row["embedding"])
            score = _cosine_similarity(query_embedding, emb)
            if score >= threshold:
                d = dict(row)
                d["embedding"] = emb
                d["metadata"] = json.loads(d["metadata"])
                scored.append((score, d))
        scored.sort(key=lambda x: x[0], reverse=True)
        return [{**d, "score": round(s, 6)} for s, d in scored[:k]]

    def list_memories(self, namespace=None, limit=100, offset=0, sort_by="created_at",
                      updated_after=None, updated_before=None, keywords=None):
        sort_col = sort_by if sort_by in ("created_at", "updated_at") else "created_at"
        clauses = ["deleted = 0"]
        params = []
        if namespace:
            clauses.append("namespace = ?")
            params.append(namespace)
        if updated_after:
            clauses.append("updated_at > ?")
            params.append(updated_after)
        if updated_before:
            clauses.append("updated_at < ?")
            params.append(updated_before)
        # Keyword filter (OR): match any keyword. Empty/None disables the filter.
        kw_list = self._extract_keywords({"keywords": keywords}) if keywords else []
        if kw_list:
            placeholders = ",".join(["?"] * len(kw_list))
            clauses.append(
                f"id IN (SELECT mk.memory_id FROM memory_keywords mk "
                f"JOIN keywords k ON k.id = mk.keyword_id "
                f"WHERE k.name IN ({placeholders}))"
            )
            params.extend(kw_list)
        params.extend([limit, offset])
        with self._lock:
            rows = self.conn.execute(
                f"SELECT * FROM memories WHERE {' AND '.join(clauses)} "
                f"ORDER BY {sort_col} DESC LIMIT ? OFFSET ?",
                params,
            ).fetchall()
        return [self._row_to_dict(r) for r in rows]

    def get(self, memory_id):
        row = self.conn.execute(
            "SELECT * FROM memories WHERE id = ? AND deleted = 0", (memory_id,)
        ).fetchone()
        return self._row_to_dict(row) if row else None

    def update(self, memory_id, text=None, embedding=None, metadata=None, namespace=None, summary=None):
        with self._lock:
            existing = self.get(memory_id)
            if not existing:
                return False
            now = _now()
            text = text if text is not None else existing["text"]
            emb = embedding if embedding is not None else existing["embedding"]
            meta = {**existing["metadata"], **(metadata or {})}
            ns = namespace if namespace is not None else existing["namespace"]
            summ = summary if summary is not None else existing.get("summary")
            self.conn.execute(
                "UPDATE memories SET text = ?, embedding = ?, metadata = ?, "
                "namespace = ?, updated_at = ?, synced = 0, summary = ? WHERE id = ?",
                (text, self._serialize(emb), json.dumps(meta), ns, now, summ, memory_id),
            )
            # Only touch the keyword index when the caller explicitly provided
            # a keywords key in metadata (update semantics: replace the whole array).
            if metadata is not None and "keywords" in metadata:
                self._sync_keyword_index(memory_id, meta)
            self.conn.commit()
        return True

    def update_summary(self, memory_id, summary):
        """Update only the summary field — updated_at stays unchanged."""
        with self._lock:
            c = self.conn.execute(
                "UPDATE memories SET summary = ?, synced = 0 WHERE id = ? AND deleted = 0",
                (summary, memory_id),
            )
            self.conn.commit()
        return c.rowcount > 0

    def update_metadata(self, memory_id, metadata):
        """Merge metadata and re-sync the keyword index — updated_at stays
        unchanged. Used by the keyword-extraction migration so backfilled
        keywords do not perturb time-based list ordering.

        ``metadata`` keys overwrite existing ones (shallow merge). When the
        merged metadata carries a ``keywords`` key, the index is rebuilt for
        this memory; otherwise the keyword index is left untouched.
        """
        with self._lock:
            existing = self.get(memory_id)
            if not existing:
                return False
            merged = {**existing["metadata"], **(metadata or {})}
            self.conn.execute(
                "UPDATE memories SET metadata = ?, synced = 0 WHERE id = ? AND deleted = 0",
                (json.dumps(merged), memory_id),
            )
            if metadata is not None and "keywords" in metadata:
                self._sync_keyword_index(memory_id, merged)
            self.conn.commit()
        return True

    def get_pending_summaries(self, limit=1000):
        """Records with empty summary, oldest first (background worker recovery)."""
        with self._lock:
            rows = self.conn.execute(
                "SELECT * FROM memories WHERE deleted = 0 "
                "AND (summary IS NULL OR summary = '') ORDER BY created_at ASC LIMIT ?",
                (limit,),
            ).fetchall()
        return [self._row_to_dict(r) for r in rows]

    def get_details(self, memory_ids):
        """Fetch full records by ID list. Partial success: missing IDs are reported."""
        found, missing = [], []
        if not memory_ids:
            return {"found": found, "missing": missing}
        with self._lock:
            placeholders = ",".join(["?"] * len(memory_ids))
            rows = self.conn.execute(
                f"SELECT * FROM memories WHERE deleted = 0 AND id IN ({placeholders})",
                memory_ids,
            ).fetchall()
            by_id = {r["id"]: self._row_to_dict(r) for r in rows}
        for mid in memory_ids:
            if mid in by_id:
                found.append(by_id[mid])
            else:
                missing.append(mid)
        return {"found": found, "missing": missing}

    def delete(self, memory_id):
        """Soft-delete: mark as deleted and unsynced."""
        with self._lock:
            c = self.conn.execute(
                "UPDATE memories SET deleted = 1, synced = 0, updated_at = ? WHERE id = ? AND deleted = 0",
                (_now(), memory_id),
            )
            if c.rowcount > 0:
                self._remove_keyword_associations(memory_id)
            self.conn.commit()
        return c.rowcount > 0

    def clear(self, namespace=None):
        """Soft-clear: mark all as deleted and unsynced."""
        with self._lock:
            if namespace:
                n = self.conn.execute(
                    "SELECT COUNT(*) FROM memories WHERE namespace = ? AND deleted = 0",
                    (namespace,),
                ).fetchone()[0]
                self.conn.execute(
                    "UPDATE memories SET deleted = 1, synced = 0, updated_at = ? WHERE namespace = ? AND deleted = 0",
                    (_now(), namespace),
                )
                self.conn.execute(
                    "DELETE FROM memory_keywords WHERE memory_id IN "
                    "(SELECT id FROM memories WHERE namespace = ?)",
                    (namespace,),
                )
            else:
                n = self.conn.execute(
                    "SELECT COUNT(*) FROM memories WHERE deleted = 0"
                ).fetchone()[0]
                self.conn.execute(
                    "UPDATE memories SET deleted = 1, synced = 0, updated_at = ? WHERE deleted = 0",
                    (_now(),),
                )
                self.conn.execute("DELETE FROM memory_keywords")
            self.conn.commit()
        return n

    def merge(self, source_storage, namespace_prefix=""):
        imported = 0
        renamed = 0
        skipped = 0
        imported_ids = []
        with self._lock:
            existing_ids = set(
                row[0]
                for row in self.conn.execute("SELECT id FROM memories WHERE deleted = 0").fetchall()
            )
            existing_pairs = set(
                (row[0], row[1])
                for row in self.conn.execute(
                    "SELECT namespace, text FROM memories WHERE deleted = 0"
                ).fetchall()
            )
            src_memories = source_storage.list_memories(limit=10 ** 9)
            for m in src_memories:
                ns = namespace_prefix + m["namespace"]
                # Dedup on content + namespace: already present → skip.
                if (ns, m["text"]) in existing_pairs:
                    skipped += 1
                    continue
                mid = m["id"]
                if mid in existing_ids:
                    mid = _new_id()
                    renamed += 1
                existing_ids.add(mid)
                existing_pairs.add((ns, m["text"]))
                self.conn.execute(
                    "INSERT INTO memories (id, text, embedding, metadata, namespace, created_at, updated_at, synced, summary) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?, 0, ?)",
                    (mid, m["text"], self._serialize(m["embedding"]),
                     json.dumps(m["metadata"]), ns, m["created_at"], m["updated_at"],
                     m.get("summary")),
                )
                self._sync_keyword_index(mid, m.get("metadata") or {})
                imported += 1
                imported_ids.append(mid)
            self.conn.commit()
        return {"imported": imported, "skipped": skipped, "renamed": renamed,
                "total": len(src_memories), "imported_ids": imported_ids}

    def get_stats(self):
        with self._lock:
            total = self.conn.execute(
                "SELECT COUNT(*) FROM memories WHERE deleted = 0"
            ).fetchone()[0]
            ns_rows = self.conn.execute(
                "SELECT namespace, COUNT(*) as cnt FROM memories WHERE deleted = 0 GROUP BY namespace"
            ).fetchall()
            keyword_counts = self._keyword_counts()
        return {
            "total": total,
            "namespaces": [r["namespace"] for r in ns_rows],
            "namespace_counts": {r["namespace"]: r["cnt"] for r in ns_rows},
            "keyword_counts": keyword_counts,
            "backend": "sqlite",
            "path": self.path,
        }
